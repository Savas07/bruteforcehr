# Lockup on a 100-unit-high grid: plate 100, gap 28, text set at 100 units with cap height centred on the
# plate; "BruteForce" in the primary text colour, "HR" in the accent text colour (wordmark critique r1).
WORDMARK_GAP = 28
WORDMARK_TRACKING = -0.005  # em
WORDMARK_COLORS = {
    "light": ("#161A22", "#1F635D"),  # fg.primary, accent.text (light)
    "dark": ("#ECEEF2", "#43BEB4"),  # fg.primary, accent.text (dark)
}


def outline_text(font_path: Path, text: str, size: float) -> tuple[str, float, float]:
    """Shaped (kerned) outline of `text` with its baseline at y=0: (path data, advance, cap height)."""
    import uharfbuzz as hb  # noqa: PLC0415 — only this command needs the font toolchain
    from fontTools.pens.svgPathPen import SVGPathPen  # noqa: PLC0415
    from fontTools.pens.transformPen import TransformPen  # noqa: PLC0415
    from fontTools.ttLib import TTFont  # noqa: PLC0415

    face = hb.Face(hb.Blob.from_file_path(str(font_path)))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(hb.Font(face), buf, {"kern": True, "liga": True})
    tt = TTFont(str(font_path))
    glyphs, order = tt.getGlyphSet(), tt.getGlyphOrder()
    scale = size / face.upem
    x, d = 0.0, []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions, strict=True):
        pen = SVGPathPen(glyphs, lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
        glyphs[order[info.codepoint]].draw(TransformPen(pen, (scale, 0, 0, -scale, (x + pos.x_offset) * scale, 0)))
        d.append(pen.getCommands())
        x += pos.x_advance + WORDMARK_TRACKING * face.upem
    return "".join(d), (x - WORDMARK_TRACKING * face.upem) * scale, tt["OS/2"].sCapHeight * scale


def wordmark(font_path: Path) -> None:
    mark = re.search(r'd="([^"]+)"', (BRAND / "mark.svg").read_text())
    assert mark
    brute, brute_w, cap = outline_text(font_path, "BruteForce", 100)
    hr, hr_w, _ = outline_text(font_path, "HR", 100)
    baseline = (100 + cap) / 2
    x_brute = 100 + WORDMARK_GAP
    x_hr = x_brute + brute_w
    width = f"{x_hr + hr_w:.2f}"
    plate = f'<rect width="100" height="100" rx="18.75" fill="url(#GRADIENT_ID)"/>'
    glyph = f'<path transform="scale(0.09765625)" fill="#FFFFFF" d="{mark.group(1)}"/>'
    gradient = GRADIENT.replace('id="bg"', 'id="GRADIENT_ID"')

    def text(fill_brute: str, fill_hr: str) -> str:
        return (
            f'<path transform="translate({x_brute:.2f} {baseline:.2f})" fill="{fill_brute}" d="{brute}"/>'
            f'<path transform="translate({x_hr:.2f} {baseline:.2f})" fill="{fill_hr}" d="{hr}"/>'
        )

    for scheme, (fg, accent) in WORDMARK_COLORS.items():
        name = "wordmark.svg" if scheme == "light" else "wordmark-dark.svg"
        body = f"<defs>{gradient}</defs>{plate}{glyph}{text(fg, accent)}".replace("GRADIENT_ID", "bg")
        (BRAND / name).write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} 100" role="img" aria-label="BruteForceHR">'
            f"<title>BruteForceHR</title>{body}</svg>\n"
        )
    WEB_WORDMARK.write_text(
        "---\n"
        "/**\n"
        " * BruteForceHR wordmark: app-icon plate + \"BruteForce\" (current text colour) + \"HR\" (`accent.text`).\n"
        " * Generated by `design/brand/build.py wordmark` from design/brand/mark.svg and Inter Display SemiBold\n"
        " * (OFL 1.1) outlines; edit the generator, not this file. Critique: docs/design/critiques/brand/wordmark.\n"
        " * `gradientId` must be unique per page (the plate's gradient is referenced by id).\n"
        " */\n"
        'import { SITE_NAME } from "../site.ts";\n\n'
        "interface Props {\n"
        "  gradientId: string;\n"
        "  class?: string;\n"
        "}\n\n"
        "const { gradientId, class: className } = Astro.props;\n"
        "---\n\n"
        f'<svg class={{className}} viewBox="0 0 {width} 100" role="img" aria-label={{SITE_NAME}}>\n'
        f"  <defs>{gradient.replace('id=\"GRADIENT_ID\"', 'id={gradientId}')}</defs>\n"
        f"  {plate.replace('"url(#GRADIENT_ID)"', '{`url(#${gradientId})`}')}\n"
        f"  {glyph}\n"
        f"  {text('currentColor', 'var(--bfhr-color-accent-text)')}\n"
        "</svg>\n"
    )


