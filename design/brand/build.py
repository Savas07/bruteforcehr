def srgb(hex_color: str) -> str:
    r, g, b = (int(hex_color[i : i + 2], 16) / 255 for i in (1, 3, 5))
    return f"extended-srgb:{r:.5f},{g:.5f},{b:.5f},1.00000"


def icon_composer_document() -> dict:
    """Icon Composer (`.icon`) document: teal background, one Liquid Glass group holding the white mark.
    Dark: near-black background, teal mark. Tinted and clear are derived by the system from these layers."""
    return {
        "fill-specializations": [
            {"value": {"linear-gradient": [srgb(BG_TOP), srgb(BG_BOTTOM)]}},
            {"appearance": "dark", "value": {"linear-gradient": [srgb(DARK_BG_TOP), srgb(DARK_BG_BOTTOM)]}},
        ],
        "groups": [
            {
                "name": "Mark",
                "layers": [
                    {
                        "name": "B",
                        "image-name": "mark.svg",
                        "glass": True,
                        "fill-specializations": [
                            {"value": "automatic"},
                            {"appearance": "dark", "value": {"solid": srgb(DARK_GLYPH)}},
                        ],
                    }
                ],
                "shadow": {"kind": "neutral", "opacity": 0.5},
                "specular": True,
                # 0.2 instead of Icon Composer's default 0.5 keeps the B solid white at 29 pt (r2 finding 1).
                "translucency": {"enabled": True, "value": 0.2},
            }
        ],
        "supported-platforms": {"squares": ["iOS", "macOS"]},
    }


def write_icon_composer(dest: Path) -> None:
    if dest.exists():
        shutil.rmtree(dest)
    (dest / "Assets").mkdir(parents=True)
    shutil.copyfile(BRAND / "mark.svg", dest / "Assets/mark.svg")
    (dest / "icon.json").write_text(json.dumps(icon_composer_document(), indent=2) + "\n")


def write_ico(pngs: list[Path], dest: Path) -> None:
    """ICO container with PNG-compressed entries (Vista+), in the given order."""
    data = [p.read_bytes() for p in pngs]
    offset = 6 + 16 * len(data)
    entries = b""
    for blob in data:
        width, height = struct.unpack(">II", blob[16:24])
        entries += struct.pack("<BBBBHHII", width % 256, height % 256, 0, 0, 1, 32, len(blob), offset)
        offset += len(blob)
    dest.write_bytes(struct.pack("<HHH", 0, 1, len(data)) + entries + b"".join(data))


def write_icns(r: Renderer, work: Path, dest: Path) -> None:
    iconset = work / "icon.iconset"
    iconset.mkdir()
    for points in (16, 32, 128, 256, 512):
        shutil.copyfile(r.png("macos", points), iconset / f"icon_{points}x{points}.png")
        shutil.copyfile(r.png("macos", points * 2), iconset / f"icon_{points}x{points}@2x.png")
    run("iconutil", "-c", "icns", iconset, "-o", dest)


def write_desktop(r: Renderer, work: Path) -> None:
    """Tauri `bundle.icon`: `tauri icon` renders the PNG set from the 1024 plate; the 32 px PNG and the ICO's
    16/24/32 layers are replaced by the pixel-grid masters, the ICNS uses the macOS grid, and `AppIcon.icon`
    gives macOS 26+ its Liquid Glass icon (Tauri compiles it into Assets.car)."""
    out = work / "tauri"
    run("pnpm", "exec", "tauri", "icon", r.png("plate", 1024), "-o", out, cwd=ROOT / "apps/desktop")
    for name in ("128x128.png", "128x128@2x.png"):
        shutil.copyfile(out / name, DESKTOP_ICONS / name)
    shutil.copyfile(r.png("plate", 32), DESKTOP_ICONS / "32x32.png")
    # ICO layers 16, 24, 32, 48, 64, 256 (Tauri's requirement); 32 first so dev builds pick it.
    write_ico([r.png("plate", s) for s in (32, 16, 24, 48, 64, 256)], DESKTOP_ICONS / "icon.ico")
    write_icns(r, work, DESKTOP_ICONS / "icon.icns")
    write_icon_composer(DESKTOP_ICONS / "AppIcon.icon")


def write_web(r: Renderer) -> None:
    """favicon.svg (16 px grid, crisp at 16 and 32), favicon.ico (16/32/48) and the 180 px apple-touch-icon."""
    favicon = compose(glyph_body((BRAND / "mark-16.svg").read_text()), "plate", 16)
    (WEB_PUBLIC / "favicon.svg").write_text(favicon)
    write_ico([r.png("plate", s) for s in (16, 32, 48)], WEB_PUBLIC / "favicon.ico")
    run(
        "magick", r.png("ios", 180), "-alpha", "off", "-define", "png:exclude-chunks=date,time",
        WEB_PUBLIC / "apple-touch-icon.png",
    )


def assets() -> None:
    work = Path(tempfile.mkdtemp(prefix="bfhr-assets-"))
    try:
        r = brand_renderer(work)
        write_icon_composer(IOS_APP_ICON)
        write_desktop(r, work)
        write_web(r)
    finally:
        shutil.rmtree(work)


