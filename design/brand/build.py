#!/usr/bin/env python3
"""BruteForceHR brand pipeline: app-icon assets for every platform from the SVG masters in this folder.

Sources (white artwork on a transparent canvas):
  mark.svg                      1024 master (iOS, macOS, large Windows/Linux/web sizes)
  mark-16.svg / -24 / -32.svg   pixel-grid masters for 16/24/32 px (favicon, ICO, ICNS small entries)

  wordmark.svg / -dark.svg      lockup (mark + "BruteForce" + "HR"), generated by `wordmark`

Commands:
  build.py assets               write every platform asset into the apps (see `assets()`)
  build.py wordmark FONT.ttf    outline the wordmark from Inter Display SemiBold (OFL 1.1, rsms/inter v4.1
                                `extras/ttf/InterDisplay-SemiBold.ttf`); needs `pip install fonttools uharfbuzz`
  build.py review OUT_DIR       size sheet + Liquid Glass appearance sheet of the shipped assets
  build.py sheet OUT.png GLYPH.svg [GLYPH.svg ...]
                                concept size sheet: vector renders of 1024 glyphs at every platform size

Requires resvg (`brew install resvg`), ImageMagick, Google Chrome, Xcode 26+ (iconutil, Icon Composer's
ictool) and the workspace's Tauri CLI (`pnpm install`).
"""

from __future__ import annotations

import html
import json
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / "design/brand"
IOS_APP_ICON = ROOT / "apps/ios/BruteForceHR/AppIcon.icon"
DESKTOP_ICONS = ROOT / "apps/desktop/src-tauri/icons"
WEB_PUBLIC = ROOT / "apps/web/public"
WEB_WORDMARK = ROOT / "apps/web/src/components/Wordmark.astro"

CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
ICTOOL = "/Applications/Xcode.app/Contents/Applications/Icon Composer.app/Contents/Executables/ictool"

# Teal family from @bfhr/ui-tokens (packages/ui-tokens/src/color.ts).
BG_TOP = "#2B827B"  # accent.solid (dark scheme)
BG_BOTTOM = "#1B5954"  # accent.hover (light scheme)
DARK_BG_TOP = "#1E2229"  # surface.elevated (dark)
DARK_BG_BOTTOM = "#0E1014"  # surface.canvas (dark)
DARK_GLYPH = "#43BEB4"  # accent.text (dark)

GRADIENT = (
    '<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">'
    f'<stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOTTOM}"/>'
    "</linearGradient>"
)

# Apple macOS app-icon grid (Big Sur and later): 824 body centred on a 1024 canvas, drop shadow.
MAC_BODY = 824
MAC_RADIUS = 185.4
# Windows / Linux / web plate: full canvas, 3/16 corner radius (3 px at 16 px).
PLATE_RADIUS_RATIO = 3 / 16

SMALL_MASTERS = (16, 24, 32)
SHEET_SIZES = {
    "ios": [180, 120, 87, 80, 60, 58, 40],
    "macos": [128, 64, 32, 16],
    "windows": [48, 32, 24, 16],
}


def run(*cmd: str | Path, cwd: Path | None = None) -> None:
    subprocess.run([str(c) for c in cmd], check=True, cwd=cwd, capture_output=True)


def glyph_body(svg: str) -> str:
    """Inner markup of a glyph SVG without comments."""
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not inner:
        raise ValueError("not an SVG document")
    return re.sub(r"<!--.*?-->", "", inner.group(1), flags=re.S).strip()


def doc(size: float, body: str, defs: str = "") -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size:g} {size:g}" width="{size:g}" height="{size:g}">'
        f"<defs>{GRADIENT}{defs}</defs>{body}</svg>\n"
    )


def compose(glyph: str, variant: str, canvas: int = 1024) -> str:
    """Background + glyph on a `canvas`-unit grid.
    `ios`: full-bleed square (the system applies the mask). `macos`: Apple-grid body with shadow at 1024, a
    1/16-inset body without shadow on the 16/32 pixel grids. `plate`: rounded square for Windows, Linux, web."""
    if variant == "ios":
        return doc(canvas, f'<rect width="{canvas}" height="{canvas}" fill="url(#bg)"/>{glyph}')
    if variant == "plate":
        r = canvas * PLATE_RADIUS_RATIO
        return doc(canvas, f'<rect width="{canvas}" height="{canvas}" rx="{r:g}" fill="url(#bg)"/>{glyph}')
    if variant == "macos" and canvas == 1024:
        inset = (1024 - MAC_BODY) / 2
        shadow = (
            '<filter id="shadow" x="-10%" y="-10%" width="120%" height="125%">'
            '<feDropShadow dx="0" dy="10" stdDeviation="10" flood-color="#000000" flood-opacity="0.3"/>'
            "</filter>"
        )
        return doc(
            1024,
            f'<rect x="{inset:g}" y="{inset:g}" width="{MAC_BODY}" height="{MAC_BODY}" rx="{MAC_RADIUS}" '
            f'fill="url(#bg)" filter="url(#shadow)"/>'
            f'<g transform="translate({inset:g} {inset:g}) scale({MAC_BODY / 1024:g})">{glyph}</g>',
            shadow,
        )
    if variant == "macos":
        inset = canvas / 16
        body = canvas - 2 * inset
        return doc(
            canvas,
            f'<rect x="{inset:g}" y="{inset:g}" width="{body:g}" height="{body:g}" rx="{body * MAC_RADIUS / MAC_BODY:.2f}" '
            f'fill="url(#bg)"/>{glyph}',
        )
    raise ValueError(variant)


class Renderer:
    """PNG renders of one glyph's variants. Sizes with a pixel-grid master use it (except for iOS, where the
    smallest asset is 40 px and the system scales); everything else renders the 1024 master as vectors."""

    def __init__(self, work: Path, name: str, glyph: Path, small: dict[int, Path] | None = None) -> None:
        self.work = work
        self.name = name
        self.glyph = glyph_body(glyph.read_text())
        self.small = {n: glyph_body(p.read_text()) for n, p in (small or {}).items()}

    def svg(self, variant: str, size: int) -> Path:
        canvas = size if size in self.small and variant != "ios" else 1024
        glyph = self.small[size] if canvas != 1024 else self.glyph
        path = self.work / f"{self.name}-{variant}-{canvas}.svg"
        if not path.exists():
            path.write_text(compose(glyph, variant, canvas))
        return path

    def png(self, variant: str, size: int) -> Path:
        out = self.work / f"{self.name}-{variant}-{size}.png"
        if not out.exists():
            run("resvg", "-w", str(size), "-h", str(size), self.svg(variant, size), out)
        return out


def brand_renderer(work: Path) -> Renderer:
    return Renderer(work, "mark", BRAND / "mark.svg", {n: BRAND / f"mark-{n}.svg" for n in SMALL_MASTERS})


