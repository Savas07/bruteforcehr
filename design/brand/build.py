def fig(src: Path, label: str, shown: int) -> str:
    return (
        f'<figure><img src="{src.name}" width="{shown}" height="{shown}" alt="">'
        f"<figcaption>{html.escape(label)}</figcaption></figure>"
    )


def size_section(r: Renderer, title: str, note: str) -> str:
    png: Callable[[str, int], Path] = r.png
    schemes = []
    for scheme in ("light", "dark"):
        ios = "".join(fig(png("ios", s), str(s), s) for s in SHEET_SIZES["ios"])
        mac = "".join(fig(png("macos", s), str(s), s) for s in SHEET_SIZES["macos"])
        win = "".join(fig(png("plate", s), str(s), s) for s in SHEET_SIZES["windows"])
        zoom = "".join(
            fig(png(v, s), f"{label} {s} ×{z}", s * z)
            for v, s, z, label in (("plate", 16, 8, "favicon"), ("plate", 32, 4, "favicon"), ("macos", 16, 8, "macOS"))
        )
        schemes.append(
            f'<div class="scheme {scheme}"><h2>{html.escape(title)} · {scheme}</h2>'
            "<h3>Large sizes, scaled to 128 px: iOS 1024 (system mask) · macOS 1024 / 512 · Windows 256</h3>"
            f'<div class="row"><div class="ios">{fig(png("ios", 1024), "iOS 1024", 128)}</div>'
            f'{fig(png("macos", 1024), "macOS 1024", 128)}{fig(png("macos", 512), "macOS 512", 128)}'
            f'{fig(png("plate", 256), "Windows 256", 128)}</div>'
            f'<h3>iOS · actual px</h3><div class="row ios">{ios}</div>'
            f'<h3>macOS · actual px</h3><div class="row">{mac}</div>'
            f'<h3>Windows plate · actual px · taskbar at 24</h3><div class="row">{win}'
            f'<div class="taskbar"><span><img src="{png("plate", 24).name}" width="24" height="24" alt=""></span></div></div>'
            '<h3>Favicon · browser tab at 1×</h3><div class="row"><div class="tab">'
            f'<img src="{png("plate", 16).name}" width="16" height="16" alt="">BruteForceHR</div>'
            f'{fig(png("plate", 32), "32", 32)}{fig(png("plate", 16), "16", 16)}</div>'
            f'<h3>Pixel zoom (nearest neighbour)</h3><div class="row zoom">{zoom}</div></div>'
        )
    return f'<section><div class="pair">{"".join(schemes)}</div><p class="note">{html.escape(note)}</p></section>'


def write_sheet(work: Path, sections: list[str], out: Path, height: int) -> None:
    page = work / "sheet.html"
    page.write_text(f"<!doctype html><meta charset=utf-8><style>{SHEET_CSS}</style>{''.join(sections)}")
    screenshot(page, out, 1640, height)


def concept_sheet(out: Path, glyph_paths: list[Path]) -> None:
    work = Path(tempfile.mkdtemp(prefix="bfhr-sheet-"))
    try:
        sections = []
        for path in glyph_paths:
            note = re.search(r"<!--\s*(.*?)\s*-->", path.read_text(), re.S)
            sections.append(size_section(Renderer(work, path.stem, path), path.stem, note.group(1) if note else ""))
        write_sheet(work, sections, out, 1200 * len(glyph_paths))
    finally:
        shutil.rmtree(work)


RENDITIONS = ("Default", "Dark", "TintedLight", "TintedDark", "ClearLight", "ClearDark")


def appearance_section(work: Path) -> str:
    """Icon Composer renditions of the shipped AppIcon.icon on iOS and macOS, at 128 and at Home Screen /
    Spotlight / Settings sizes (60, 40, 29 pt at 2x), on a mid-grey wallpaper like the Icon Composer canvas."""
    rows = []
    for platform in ("iOS", "macOS"):
        cells = []
        for rendition in RENDITIONS:
            figs = []
            for points, shown in ((128, 128), (60, 60), (40, 40), (29, 29)):
                out = work / f"ic-{platform}-{rendition}-{points}.png"
                run(ICTOOL, IOS_APP_ICON, "--export-image", "--output-file", out, "--platform", platform,
                    "--rendition", rendition, "--width", str(points), "--height", str(points), "--scale", "2")
                figs.append(fig(out, f"{points} pt" if points != 128 else rendition, shown))
            cells.append(f'<div class="row" style="gap:8px">{"".join(figs)}</div>')
        rows.append(
            f'<h3>{platform}</h3><div style="display:grid;grid-template-columns:repeat(3,auto);gap:16px 28px;'
            f'justify-content:start">{"".join(cells)}</div>'
        )
    return (
        '<section class="scheme" style="background:#8A9099;color:#FFFFFF"><h2>AppIcon.icon · Icon Composer renditions'
        f' (ictool)</h2>{"".join(rows)}</section>'
    )


def review(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="bfhr-review-"))
    try:
        r = brand_renderer(work)
        note = "Shipped assets: mark.svg for 1024-derived sizes; mark-16/24/32.svg pixel-grid masters at 16, 24, 32 px."
        write_sheet(work, [size_section(r, "BruteForceHR app icon", note)], out_dir / "sizes.png", 1200)
        write_sheet(work, [appearance_section(work)], out_dir / "appearances.png", 900)
    finally:
        shutil.rmtree(work)


def main(argv: list[str]) -> int:
    if argv == ["assets"]:
        assets()
        return 0
    if len(argv) == 2 and argv[0] == "wordmark":
        wordmark(Path(argv[1]).resolve())
        return 0
    if len(argv) == 2 and argv[0] == "review":
        review(Path(argv[1]).resolve())
        return 0
    if len(argv) >= 3 and argv[0] == "sheet":
        concept_sheet(Path(argv[1]).resolve(), [Path(p).resolve() for p in argv[2:]])
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
