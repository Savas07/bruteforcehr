def screenshot(page: Path, out: Path, width: int, height: int) -> None:
    run(
        CHROME,
        "--headless=new",
        "--hide-scrollbars",
        "--force-device-scale-factor=1",
        f"--window-size={width},{height}",
        f"--screenshot={out}",
        page.as_uri(),
    )
    run("magick", out, "-trim", "+repage", out)


