import type { CoverLetterResult } from "../../src/cover-letter";
import type { CvTailorResult } from "../../src/cv-tailor";
import { LETTER_CASES, TAILOR_CASES } from "./fixtures";
import { type ApplyMetrics, gateFailures, type LetterCaseScore, type TailorCaseScore } from "./score";

const usd = (microUsd: number): string => `$${(microUsd / 1e6).toFixed(4)}`;
const pct = (part: number, whole: number): string =>
  whole === 0 ? "—" : `${((100 * part) / whole).toFixed(0)} %`;

export interface ApplyReportInput {
  model: string;
  tailorPromptVersion: string;
  letterPromptVersion: string;
  recordedAt: string;
  metrics: ApplyMetrics;
  tailor: { score: TailorCaseScore; result: CvTailorResult }[];
  letters: { score: LetterCaseScore; result: CoverLetterResult }[];
}

export function renderApplyReport(input: ApplyReportInput): string {
  const { metrics: m } = input;
  const failures = gateFailures(m);
  const totalCost = m.tailorCostMicroUsd + m.letterCostMicroUsd;
  const lines = [
    `# Apply eval — ${input.model}`,
    "",
    `Prompts \`${input.tailorPromptVersion}\` and \`${input.letterPromptVersion}\`, recorded ${input.recordedAt}. Generated by \`pnpm --filter @bfhr/ai eval:apply\`; CI replays the recording (\`eval/apply/gate.test.ts\`). Fixtures: ${TAILOR_CASES.length} postings for 12 import-eval CVs (4 EN, 4 TR, 4 DE; two postings in English for a Turkish and a German CV), each asking for things the CV lacks (bait).`,
    "",
    "## Gate",
    "",
    failures.length === 0 ? "**Pass.**" : `**Fail:** ${failures.join("; ")}.`,
    "",
    `- **Fabricated items: ${m.fabrications}** (independent audit: every number, date and entity in an edit must be in the CV, every one in a letter in the CV, the posting or the template; no bait term in an edit or a first-person letter sentence; no digit run the sources lack)`,
    `- Tailoring cases with edits: ${m.tailorWithEdits}/${m.tailorCases} (gate ≥ 75 %); all accepted edits apply cleanly: ${m.tailorAppliesCleanly}/${m.tailorCases}`,
    `- Letters in the requested language: ${m.letterLanguageOk}/${m.letterLanguageChecked} detectable (gate ≥ 90 %); naming the company: ${m.letterCompany}/${m.letterCases} (gate 100 %)`,
    "",
    "## Quality",
    "",
    `- Tailoring: ${m.tailorEdits} edits kept, ${m.tailorDropped} proposals dropped by the checks (${pct(m.tailorDropped, m.tailorEdits + m.tailorDropped)} of proposals). Posting keywords the CV supports appear ${m.keywordMentionsBefore} → ${m.keywordMentionsAfter} times with every edit accepted. Reasons in the UI language: ${m.reasonsInLocale}/${m.reasonsChecked} detectable.`,
    `- Cover letters: role named in ${m.letterRole}/${m.letterCases}; ${m.letterDroppedSentences} sentences removed by the grounding check; ${m.letterRetries} letter(s) needed the retry.`,
    "",
    "## Cost",
    "",
    `| | Total | Per request |`,
    `|---|---|---|`,
    `| Tailoring | ${usd(m.tailorCostMicroUsd)} | ${usd(m.tailorCostMicroUsd / Math.max(1, m.tailorCases))} |`,
    `| Cover letters | ${usd(m.letterCostMicroUsd)} | ${usd(m.letterCostMicroUsd / Math.max(1, m.letterCases))} |`,
    `| **All** | **${usd(totalCost)}** | |`,
    "",
    "## Tailoring cases",
    "",
    "| Case | Intensity | Edits | Dropped (path / invalid / ungrounded / job term) | Keyword mentions | Reasons in locale | Tokens in / out | Cost | Fabricated |",
    "|---|---|---|---|---|---|---|---|---|",
    ...input.tailor.map(({ score: s }) => {
      const testCase = TAILOR_CASES.find((candidate) => candidate.id === s.id);
      const d = s.dropReasons;
      return `| ${s.id} | ${testCase?.intensity ?? ""} | ${s.edits} | ${s.dropped} (${d.path} / ${d.invalid} / ${d.ungrounded} / ${d.job_term}) | ${s.keywordMentionsBefore} → ${s.keywordMentionsAfter} | ${s.reasonsInLocale}/${s.reasonsChecked} | ${s.inputTokens} / ${s.outputTokens} | ${usd(s.costMicroUsd)} | ${s.fabrications.length} |`;
    }),
    "",
    "## Cover letter cases",
    "",
    "| Case | Tone | Template | Words | Language | Company / role | Placeholders | Dropped | Calls | Cost | Fabricated |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
    ...input.letters.map(({ score: s }) => {
      const testCase = LETTER_CASES.find((candidate) => candidate.id === s.id);
      return `| ${s.id} | ${testCase?.tone ?? ""} | ${testCase?.templateId ?? "—"} | ${s.words} | ${s.languageDetected ?? "?"}${s.languageOk === false ? " ✗" : ""} | ${s.mentionsCompany ? "✓" : "✗"} / ${s.mentionsRole ? "✓" : "✗"} | ${s.placeholders} | ${s.droppedSentences} | ${s.attempts} | ${usd(s.costMicroUsd)} | ${s.fabrications.length} |`;
    }),
    "",
    "## Fabrication audit",
    "",
    ...(m.fabrications === 0
      ? ["None."]
      : [...input.tailor, ...input.letters].flatMap(({ score }) =>
          score.fabrications.map((line) => `- ${line}`),
        )),
    "",
    "## Terms the checks removed",
    "",
    "Proposals and sentences dropped before they reached the user (model output the grounding check caught):",
    "",
    ...[
      ...input.tailor.map(({ score, result }) => [score.id, result.droppedTerms] as const),
      ...input.letters.map(({ score, result }) => [score.id, result.droppedTerms] as const),
    ]
      .filter(([, terms]) => terms.length > 0)
      .map(([id, terms]) => `- \`${id}\`: ${[...new Set(terms)].map((term) => `\`${term}\``).join(", ")}`),
    "",
    "## Samples",
    "",
    ...samples(input),
  ];
  return `${lines.join("\n")}\n`;
}

function samples(input: ApplyReportInput): string[] {
  const out: string[] = [];
  const tailor = input.tailor.find(({ score }) => score.id === "tailor-en-01") ?? input.tailor[0];
  if (tailor !== undefined) {
    out.push(`### ${tailor.score.id}`, "");
    for (const edit of tailor.result.edits.slice(0, 6)) {
      out.push(
        `- \`${edit.op} ${edit.path}\`: ${edit.before === null ? "" : `~~${edit.before}~~ → `}${edit.after ?? "(removed)"} — _${edit.reason}_`,
      );
    }
    out.push("");
  }
  for (const id of ["letter-en-01", "letter-de-02", "letter-tr-02"]) {
    const letter = input.letters.find(({ score }) => score.id === id);
    if (letter === undefined) continue;
    out.push(
      `### ${id}`,
      "",
      `Subject: ${letter.result.subject ?? "—"}`,
      "",
      ...letter.result.body.split("\n").map((line) => `> ${line}`),
      "",
    );
  }
  return out;
}
