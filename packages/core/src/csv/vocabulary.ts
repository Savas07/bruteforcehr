/** Lower case, diacritics and punctuation removed, Turkish ı/İ folded to i, spaces collapsed. */
export function normalizeWord(value: string): string {
  return value
    .replace(/[ıİ]/g, "i")
    .normalize("NFKD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/ß/g, "ss")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

