/**
 * Keys of `table` whose synonyms match `value`: an exact normalized match alone, else every key
 * with a synonym contained as whole words ("Interview round 2"), longest synonym first.
 */
export function matchSynonyms<Key extends string>(
  value: string,
  table: Readonly<Record<Key, readonly string[]>>,
): { readonly exact: boolean; readonly keys: readonly Key[] } {
  const word = normalizeWord(value);
  if (word === "") return { exact: false, keys: [] };
  const contained: { key: Key; length: number }[] = [];
  for (const key of Object.keys(table) as Key[]) {
    let longest = 0;
    for (const synonym of table[key]) {
      if (synonym === word) return { exact: true, keys: [key] };
      if (synonym.length > longest && ` ${word} `.includes(` ${synonym} `)) longest = synonym.length;
    }
    if (longest > 0) contained.push({ key, length: longest });
  }
  return { exact: false, keys: contained.sort((a, b) => b.length - a.length).map(({ key }) => key) };
}
