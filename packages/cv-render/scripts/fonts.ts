// Regenerates src/fonts.generated.ts (base64 WOFF2 faces, Latin + Latin Extended so Turkish and
// German glyphs are covered) and fonts/<family>/OFL.txt from the pinned @fontsource packages.
// `src/fonts.test.ts` fails when the committed output is stale.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);

interface FamilySource {
  id: string;
  family: string;
  pkg: string;
  file: (subset: string) => string;
  copyright: string;
}

const FAMILIES: FamilySource[] = [
  {
    id: "inter",
    family: "Inter",
    pkg: "@fontsource-variable/inter",
    file: (subset) => `inter-${subset}-wght-normal.woff2`,
    copyright: "Copyright 2016 The Inter Project Authors (https://github.com/rsms/inter)",
  },
  {
    id: "source-serif-4",
    family: "Source Serif 4",
    pkg: "@fontsource-variable/source-serif-4",
    file: (subset) => `source-serif-4-${subset}-wght-normal.woff2`,
    copyright: "Copyright 2014-2021 Adobe (http://www.adobe.com/), with Reserved Font Name 'Source'",
  },
  {
    id: "source-sans-3",
    family: "Source Sans 3",
    pkg: "@fontsource-variable/source-sans-3",
    file: (subset) => `source-sans-3-${subset}-wght-normal.woff2`,
    copyright: "Copyright 2010-2020 Adobe (http://www.adobe.com/), with Reserved Font Name 'Source'",
  },
];

const SUBSETS = ["latin", "latin-ext"] as const;

export async function renderFontsModule(): Promise<{ module: string; licences: Map<string, string> }> {
  const lines: string[] = [
    "// Generated by scripts/fonts.ts from @fontsource packages. Do not edit.",
    "// Fonts are licensed under the SIL Open Font License 1.1; see packages/cv-render/fonts/*/OFL.txt.",
    "",
    "export interface EmbeddedFontFace {",
    "  readonly subset: \"latin\" | \"latin-ext\";",
    "  readonly unicodeRange: string;",
    "  readonly woff2Base64: string;",
    "}",
    "",
    "export interface EmbeddedFontFamily {",
    "  readonly family: string;",
    "  readonly version: string;",
    "  readonly copyright: string;",
    "  readonly weights: string;",
    "  readonly faces: readonly EmbeddedFontFace[];",
    "}",
    "",
    "export const EMBEDDED_FONTS = {",
  ];
  const licences = new Map<string, string>();
  for (const source of FAMILIES) {
    const root = dirname(require.resolve(`${source.pkg}/package.json`));
    const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8")) as { version: string };
    const unicode = JSON.parse(await readFile(join(root, "unicode.json"), "utf8")) as Record<string, string>;
    const metadata = JSON.parse(await readFile(join(root, "metadata.json"), "utf8")) as {
      variable?: { wght?: { min: string; max: string } };
    };
    const wght = metadata.variable?.wght;
    // The @fontsource LICENSE starts with a generic copyright paragraph; use the upstream one.
    const licence = await readFile(join(root, "LICENSE"), "utf8");
    licences.set(source.id, `${source.copyright}${licence.slice(licence.indexOf("\n\n"))}`);
    lines.push(`  ${JSON.stringify(source.id)}: {`);
    lines.push(`    family: ${JSON.stringify(source.family)},`);
    lines.push(`    version: ${JSON.stringify(pkg.version)},`);
    lines.push(`    copyright: ${JSON.stringify(source.copyright)},`);
    lines.push(`    weights: ${JSON.stringify(wght ? `${wght.min} ${wght.max}` : "400 700")},`);
    lines.push("    faces: [");
    for (const subset of SUBSETS) {
      const bytes = await readFile(join(root, "files", source.file(subset)));
      const range = unicode[subset];
      if (!range) throw new Error(`${source.pkg}: no unicode range for ${subset}`);
      lines.push("      {");
      lines.push(`        subset: ${JSON.stringify(subset)},`);
      lines.push(`        unicodeRange: ${JSON.stringify(range)},`);
      lines.push(`        woff2Base64: ${JSON.stringify(bytes.toString("base64"))},`);
      lines.push("      },");
    }
    lines.push("    ],");
    lines.push("  },");
  }
  lines.push("} as const satisfies Record<string, EmbeddedFontFamily>;", "");
  lines.push("export type EmbeddedFontId = keyof typeof EMBEDDED_FONTS;", "");
  return { module: lines.join("\n"), licences };
}

if (import.meta.main) {
  const packageRoot = join(dirname(new URL(import.meta.url).pathname), "..");
  const { module, licences } = await renderFontsModule();
  await writeFile(join(packageRoot, "src/fonts.generated.ts"), module);
  for (const [id, text] of licences) {
    await mkdir(join(packageRoot, "fonts", id), { recursive: true });
    await writeFile(join(packageRoot, "fonts", id, "OFL.txt"), text);
  }
  console.log(`cv-render: wrote src/fonts.generated.ts and ${licences.size} licences`);
}
