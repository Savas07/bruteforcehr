import {
  color,
  colorSchemes,
  type ColorScheme,
  type IncreasedContrastColors,
  type SemanticColors,
} from "./color.ts";
import {
  borderWidth,
  controlHeight,
  duration,
  easing,
  elevation,
  elevationKeys,
  gridUnit,
  hitTarget,
  layer,
  motionDistance,
  radius,
  reducedMotion,
  space,
} from "./scales.ts";
import {
  fluidViewport,
  fontFamily,
  marketingTextKeys,
  marketingTextStyles,
  textStyleKeys,
  textStyles,
} from "./typography.ts";

/** Every CSS custom property this package defines starts with this prefix. */
export const cssPrefix = "--bfhr-";

const header = "/* Generated by @bfhr/ui-tokens (scripts/build.ts) from src/. Do not edit. */";

/** `largeTitle` → `large-title`, `in_progress` → `in-progress`. */
export function kebab(key: string): string {
  return key
    .replace(/_/g, "-")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();
}

const rem = (px: number) => `${px / 16}rem`;

/**
 * Flattens semantic colors to `name → value` (`surface-canvas`, `fg-on-accent`,
 * `phase-in-progress-text`, `status-offer-solid`). The names are shared by the
 * CSS variables (`--bfhr-color-<name>`), the Tailwind theme (`--color-<name>`)
 * and the Swift asset catalog (`<name>.colorset`).
 */
export function flattenColors(colors: SemanticColors | IncreasedContrastColors): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (node: object, path: string[]) => {
    for (const [key, value] of Object.entries(node)) {
      const next = [...path, kebab(key)];
      if (typeof value === "string") out[next.join("-")] = value;
      else walk(value as object, next);
    }
  };
  walk(colors, []);
  return out;
}

/**
 * Fluid `clamp()` between `fluidViewport.min` and `.max` widths: equals `min`
 * px at 375 px and `max` px at 1440 px.
 */
export function fluidClamp(minPx: number, maxPx: number): string {
  const slope = (maxPx - minPx) / (fluidViewport.max - fluidViewport.min);
  const interceptRem = Number(((minPx - slope * fluidViewport.min) / 16).toFixed(4));
  const slopeVw = Number((slope * 100).toFixed(4));
  return `clamp(${rem(minPx)}, ${interceptRem}rem + ${slopeVw}vw, ${rem(maxPx)})`;
}

function schemeDeclarations(scheme: ColorScheme): string[] {
  const lines = Object.entries(flattenColors(color[scheme])).map(
    ([name, value]) => `${cssPrefix}color-${name}: ${value};`,
  );
  for (const key of elevationKeys) {
    lines.push(`${cssPrefix}shadow-${key}: ${elevation[scheme][key].shadow};`);
  }
  return lines;
}

function staticDeclarations(): string[] {
  const lines: string[] = [];
  for (const [key, stack] of Object.entries(fontFamily)) {
    lines.push(`${cssPrefix}font-${key}: ${stack.join(", ")};`);
  }
  for (const key of textStyleKeys) {
    const style = textStyles[key];
    const name = kebab(key);
    lines.push(
      `${cssPrefix}text-${name}-size: ${rem(style.desktop.size)};`,
      `${cssPrefix}text-${name}-line-height: ${rem(style.desktop.lineHeight)};`,
      `${cssPrefix}text-${name}-weight: ${style.desktop.weight};`,
      `${cssPrefix}text-${name}-family: var(${cssPrefix}font-${style.family});`,
    );
  }
  for (const key of marketingTextKeys) {
    const style = marketingTextStyles[key];
    lines.push(
      `${cssPrefix}text-${key}-size: ${fluidClamp(style.min.size, style.max.size)};`,
      `${cssPrefix}text-${key}-line-height: ${fluidClamp(style.min.lineHeight, style.max.lineHeight)};`,
      `${cssPrefix}text-${key}-weight: ${style.weight};`,
      `${cssPrefix}text-${key}-family: var(${cssPrefix}font-${style.family});`,
    );
  }
  lines.push(`${cssPrefix}space-unit: ${rem(gridUnit)};`);
  for (const [key, px] of Object.entries(space)) lines.push(`${cssPrefix}space-${key}: ${rem(px)};`);
  for (const [key, px] of Object.entries(radius)) lines.push(`${cssPrefix}radius-${key}: ${px}px;`);
  for (const [key, px] of Object.entries(borderWidth)) lines.push(`${cssPrefix}border-${key}: ${px}px;`);
  for (const [key, ms] of Object.entries(duration)) lines.push(`${cssPrefix}duration-${key}: ${ms}ms;`);
  for (const [key, points] of Object.entries(easing)) {
    lines.push(`${cssPrefix}easing-${key}: cubic-bezier(${points.join(", ")});`);
  }
  lines.push(`${cssPrefix}motion-distance: ${motionDistance}px;`);
  for (const [key, px] of Object.entries(hitTarget))
    lines.push(`${cssPrefix}hit-target-${kebab(key)}: ${px}px;`);
  for (const [key, px] of Object.entries(controlHeight)) lines.push(`${cssPrefix}control-${key}: ${px}px;`);
  for (const [key, z] of Object.entries(layer)) lines.push(`${cssPrefix}layer-${key}: ${z};`);
  return lines;
}

const block = (selector: string, lines: string[], indent = "") =>
  [`${indent}${selector} {`, ...lines.map((line) => `${indent}  ${line}`), `${indent}}`].join("\n");

/**
 * `dist/tokens.css`: CSS variables. Light is the default; dark applies with
 * `prefers-color-scheme: dark` unless `data-theme="light"` is set on the root,
 * and anywhere under `data-theme="dark"`. Reduced motion shortens durations and
 * zeroes movement.
 */
export function renderTokensCss(): string {
  const [lightScheme, darkScheme] = colorSchemes;
  const reduced = [
    ...Object.entries(reducedMotion.duration).map(([key, ms]) => `${cssPrefix}duration-${key}: ${ms}ms;`),
    `${cssPrefix}motion-distance: ${motionDistance * reducedMotion.movement}px;`,
  ];
  return [
    header,
    "",
    block(":root", ["color-scheme: light;", ...staticDeclarations(), ...schemeDeclarations(lightScheme)]),
    "",
    block('[data-theme="light"]', ["color-scheme: light;", ...schemeDeclarations(lightScheme)]),
    "",
    "@media (prefers-color-scheme: dark) {",
    block(
      ':root:not([data-theme="light"])',
      ["color-scheme: dark;", ...schemeDeclarations(darkScheme)],
      "  ",
    ),
    "}",
    "",
    block('[data-theme="dark"]', ["color-scheme: dark;", ...schemeDeclarations(darkScheme)]),
    "",
    "@media (prefers-reduced-motion: reduce) {",
    block(":root", reduced, "  "),
    "}",
    "",
  ].join("\n");
}

/**
 * `dist/tailwind.css`: Tailwind 4 theme mapped to the variables. Default
 * colors, type sizes, radii, shadows and easings are reset so only tokens
 * exist (`bg-red-500` and `text-sm` don't compile). Import after
 * `@import "tailwindcss";`.
 */
export function renderTailwindCss(): string {
  const reset = [
    "--color-*: initial;",
    "--text-*: initial;",
    "--radius-*: initial;",
    "--shadow-*: initial;",
    "--ease-*: initial;",
    `--spacing: ${rem(gridUnit)};`,
  ];
  const mapped: string[] = [];
  for (const name of Object.keys(flattenColors(color.light))) {
    mapped.push(`--color-${name}: var(${cssPrefix}color-${name});`);
  }
  for (const key of Object.keys(fontFamily)) mapped.push(`--font-${key}: var(${cssPrefix}font-${key});`);
  for (const name of [...textStyleKeys.map(kebab), ...marketingTextKeys]) {
    mapped.push(
      `--text-${name}: var(${cssPrefix}text-${name}-size);`,
      `--text-${name}--line-height: var(${cssPrefix}text-${name}-line-height);`,
      `--text-${name}--font-weight: var(${cssPrefix}text-${name}-weight);`,
    );
  }
  for (const key of Object.keys(radius)) mapped.push(`--radius-${key}: var(${cssPrefix}radius-${key});`);
  for (const key of elevationKeys) mapped.push(`--shadow-${key}: var(${cssPrefix}shadow-${key});`);
  for (const key of Object.keys(easing)) mapped.push(`--ease-${key}: var(${cssPrefix}easing-${key});`);

  return [
    header,
    '@import "./tokens.css";',
    "",
    "/* `dark:` follows the same rules as the variables: data-theme wins over the OS setting. */",
    "@custom-variant dark {",
    '  &:where([data-theme="dark"], [data-theme="dark"] *) {',
    "    @slot;",
    "  }",
    "  @media (prefers-color-scheme: dark) {",
    '    &:where(:not([data-theme="light"], [data-theme="light"] *)) {',
    "      @slot;",
    "    }",
    "  }",
    "}",
    "",
    block("@theme", reset),
    "",
    block("@theme inline", mapped),
    "",
  ].join("\n");
}
