/** Every file of the Swift package, keyed by path relative to the package root. */
export function renderSwiftPackage(): Record<string, string> {
  const files: Record<string, string> = {
    ".gitignore": ".build/\n.swiftpm/\n",
    "Package.swift": renderPackageSwift(),
    [`${targetDir}/Tokens.swift`]: renderTokensSwift(),
    [`${swiftAssetCatalogDir}/Contents.json`]: json({ info: xcodeInfo }),
  };
  for (const [name, contents] of Object.entries(renderColorSets())) {
    files[`${swiftAssetCatalogDir}/${name}.colorset/Contents.json`] = contents;
  }
  return files;
}
