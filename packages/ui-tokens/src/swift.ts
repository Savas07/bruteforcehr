function colorSection(): string[] {
  const lines: string[] = [];
  lines.push(
    "/// Color tokens. System colors where the HIG expects them (backgrounds, `label`, separators,",
    "/// fills), brand colors from the package's asset catalog everywhere else. Every brand color",
    "/// switches with Dark Mode and, for text and control lines, Increase Contrast. Allowed",
    "/// foreground/background pairings: docs/design/system.md.",
    "public enum BFHRColor {",
    "    // MARK: System colors (HIG)",
    "",
    "#if canImport(UIKit)",
  );
  for (const [key, system] of Object.entries(appleSystemColors)) {
    lines.push(
      `    /// \`UIColor.${system.uiKit}\``,
      `    public static let ${key} = Color(uiColor: .${system.uiKit})`,
    );
  }
  lines.push("#elseif canImport(AppKit)");
  for (const [key, system] of Object.entries(appleSystemColors)) {
    lines.push(
      `    /// \`NSColor.${system.appKit}\``,
      `    public static let ${key} = Color(nsColor: .${system.appKit})`,
    );
  }
  lines.push(
    "#endif",
    "",
    "    // MARK: Brand",
    "",
    "    /// Tint for text buttons, links, icons and selected controls (= `Accent.text`). Set it once",
    "    /// at the app root with `.tint(BFHRColor.tint)`.",
    "    public static let tint = Accent.text",
  );
  for (const [group, value] of Object.entries(color.light) as [keyof SemanticColors, object][]) {
    if (group === "phase" || group === "status") continue;
    const isFeedbackTone = (feedbackTones as readonly string[]).includes(group);
    const leaves = Object.keys(value).filter((key) => !(isFeedbackTone && toneKeys[key]));
    if (leaves.length === 0) continue;
    lines.push("");
    const doc = groupDocs[group];
    if (doc !== undefined) lines.push(`    /// ${doc}`);
    lines.push(`    public enum ${camel(group).replace(/^[a-z]/, (c) => c.toUpperCase())} {`);
    for (const key of leaves) {
      const name = `${kebab(group)}-${kebab(key)}`;
      lines.push(colorDoc(name, "        "), `        public static let ${camel(key)} = ${colorRef(name)}`);
    }
    lines.push("    }");
  }
  lines.push("}", "");
  return lines;
}

