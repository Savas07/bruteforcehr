function elevationSection(): string[] {
  const shadow = (scheme: "light" | "dark", key: (typeof elevationKeys)[number]) => {
    const { color: hex, opacity, radius: blur, x, y } = elevation[scheme][key].apple;
    const { red, green, blue } = rgba(hex);
    const channel = (value: string) => `${Number.parseInt(value, 16)} / 255`;
    return `BFHRShadow(color: Color(.sRGB, red: ${channel(red)}, green: ${channel(green)}, blue: ${channel(blue)}, opacity: ${String(opacity)}), radius: ${String(blur)}, x: ${String(x)}, y: ${String(y)})`;
  };
  return [
    "public struct BFHRShadow: Hashable, Sendable {",
    "    public let color: Color",
    "    public let radius: CGFloat",
    "    public let x: CGFloat",
    "    public let y: CGFloat",
    "}",
    "",
    "/// Elevation: `raised` hovered cards and sticky bars · `overlay` popovers, menus, toasts ·",
    "/// `modal` dialogs · `drag` a lifted card or row. Don't stack levels.",
    "public enum BFHRElevation: String, CaseIterable, Sendable {",
    ...elevationKeys.map((key) => `    case ${key}`),
    "",
    "    public func shadow(for colorScheme: ColorScheme) -> BFHRShadow {",
    "        switch (self, colorScheme) {",
    ...elevationKeys.flatMap((key) => [
      `        case (.${key}, .dark): ${shadow("dark", key)}`,
      `        case (.${key}, _): ${shadow("light", key)}`,
    ]),
    "        }",
    "    }",
    "}",
    "",
    "private struct BFHRElevationModifier: ViewModifier {",
    "    let level: BFHRElevation",
    "    @Environment(\\.colorScheme) private var colorScheme",
    "",
    "    func body(content: Content) -> some View {",
    "        let shadow = level.shadow(for: colorScheme)",
    "        content.shadow(color: shadow.color, radius: shadow.radius, x: shadow.x, y: shadow.y)",
    "    }",
    "}",
    "",
    "extension View {",
    "    /// Applies the elevation shadow for the current color scheme.",
    "    public func bfhrElevation(_ level: BFHRElevation) -> some View {",
    "        modifier(BFHRElevationModifier(level: level))",
    "    }",
    "}",
    "",
  ];
}

function motionSection(): string[] {
  const durationKeys = Object.keys(duration) as (keyof typeof duration)[];
  const easingKeys = Object.keys(easing) as (keyof typeof easing)[];
  const { damping, stiffness, mass } = spring.standard;
  return [
    "/// Durations. Read `@Environment(\\.accessibilityReduceMotion)` and pass it in: under Reduce",
    "/// Motion every move becomes a short cross-fade.",
    "public enum BFHRDuration: String, CaseIterable, Sendable {",
    ...durationKeys.map((key) => `    case ${key}`),
    "",
    "    public func seconds(reduceMotion: Bool) -> TimeInterval {",
    "        switch self {",
    ...durationKeys.map(
      (key) =>
        `        case .${key}: reduceMotion ? ${seconds(reducedMotion.duration[key])} : ${seconds(duration[key])}`,
    ),
    "        }",
    "    }",
    "}",
    "",
    "/// `standard` most transitions · `enter` elements arriving · `exit` elements leaving.",
    "public enum BFHREasing: String, CaseIterable, Sendable {",
    ...easingKeys.map((key) => `    case ${key}`),
    "",
    "    public func animation(duration: TimeInterval) -> Animation {",
    "        switch self {",
    ...easingKeys.map((key) => {
      const [c0x, c0y, c1x, c1y] = easing[key];
      return `        case .${key}: .timingCurve(${String(c0x)}, ${String(c0y)}, ${String(c1x)}, ${String(c1y)}, duration: duration)`;
    }),
    "        }",
    "    }",
    "}",
    "",
    "public enum BFHRMotion {",
    "    /// The animation for a duration and easing; a cross-fade timing under Reduce Motion.",
    "    public static func animation(",
    "        _ duration: BFHRDuration,",
    "        easing: BFHREasing = .standard,",
    "        reduceMotion: Bool",
    "    ) -> Animation {",
    "        let seconds = duration.seconds(reduceMotion: reduceMotion)",
    "        return reduceMotion ? .easeInOut(duration: seconds) : easing.animation(duration: seconds)",
    "    }",
    "",
    "    /// Drags and gesture-driven motion: critically damped, no overshoot. A cross-fade timing",
    "    /// under Reduce Motion.",
    "    public static func spring(reduceMotion: Bool) -> Animation {",
    "        reduceMotion",
    "            ? .easeInOut(duration: BFHRDuration.base.seconds(reduceMotion: true))",
    `            : .interpolatingSpring(mass: ${String(mass)}, stiffness: ${String(stiffness)}, damping: ${String(damping)})`,
    "    }",
    "",
    "    /// Slide distance (pt) for toasts, popovers and arriving rows; 0 under Reduce Motion.",
    "    public static func distance(reduceMotion: Bool) -> CGFloat {",
    `        reduceMotion ? ${String(motionDistance * reducedMotion.movement)} : ${String(motionDistance)}`,
    "    }",
    "",
    "    /// Skeleton shimmer runs only without Reduce Motion.",
    "    public static func shimmer(reduceMotion: Bool) -> Bool {",
    `        reduceMotion ? ${String(reducedMotion.shimmer)} : true`,
    "    }",
    "}",
    "",
  ];
}

