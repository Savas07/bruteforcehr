const lightFlat = flattenColors(color.light);
const darkFlat = flattenColors(color.dark);
const lightHighFlat = flattenColors(increasedContrast.light);
const darkHighFlat = flattenColors(increasedContrast.dark);

/** `/// Light #F6F7F9 · dark #0E1014` (+ increased-contrast values). */
function colorDoc(name: string, indent: string): string {
  const parts = [`Light \`${lightFlat[name]}\` · dark \`${darkFlat[name]}\``];
  if (lightHighFlat[name] !== undefined) {
    parts.push(`Increase Contrast: light \`${lightHighFlat[name]}\` · dark \`${darkHighFlat[name]}\``);
  }
  return `${indent}/// ${parts.join(". ")}.`;
}

const colorRef = (name: string) => `Color("${name}", bundle: .module)`;

const toneInit = (prefix: string) =>
  `BFHRTone(text: ${colorRef(`${prefix}-text`)}, subtle: ${colorRef(`${prefix}-subtle`)}, solid: ${colorRef(`${prefix}-solid`)})`;

