const xcodeInfo = { author: "xcode", version: 1 };
const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

interface Rgba {
  red: string;
  green: string;
  blue: string;
  alpha: string;
}

function rgba(hex: string): Rgba {
  const match = /^#([0-9A-F]{2})([0-9A-F]{2})([0-9A-F]{2})([0-9A-F]{2})?$/i.exec(hex);
  if (!match) throw new Error(`Expected #RRGGBB or #RRGGBBAA, got ${hex}`);
  const [, r = "", g = "", b = "", a = "FF"] = match;
  return {
    red: `0x${r.toUpperCase()}`,
    green: `0x${g.toUpperCase()}`,
    blue: `0x${b.toUpperCase()}`,
    alpha: (Number.parseInt(a, 16) / 255).toFixed(3),
  };
}

type Appearance = { appearance: "luminosity"; value: "dark" } | { appearance: "contrast"; value: "high" };
const darkAppearance: Appearance = { appearance: "luminosity", value: "dark" };
const highContrast: Appearance = { appearance: "contrast", value: "high" };

function colorEntry(hex: string, appearances: Appearance[]) {
  const { red, green, blue, alpha } = rgba(hex);
  return {
    ...(appearances.length > 0 ? { appearances } : {}),
    color: { "color-space": "srgb", components: { alpha, blue, green, red } },
    idiom: "universal",
  };
}

/** Color set names → `Contents.json`, one per flattened token. */
export function renderColorSets(): Record<string, string> {
  const light = flattenColors(color.light);
  const dark = flattenColors(color.dark);
  const lightHigh = flattenColors(increasedContrast.light);
  const darkHigh = flattenColors(increasedContrast.dark);
  const sets: Record<string, string> = {};
  for (const [name, lightValue] of Object.entries(light)) {
    const darkValue = dark[name];
    if (darkValue === undefined) throw new Error(`No dark value for ${name}`);
    const colors = [colorEntry(lightValue, []), colorEntry(darkValue, [darkAppearance])];
    const lightHighValue = lightHigh[name];
    const darkHighValue = darkHigh[name];
    if (lightHighValue !== undefined && darkHighValue !== undefined) {
      colors.push(
        colorEntry(lightHighValue, [highContrast]),
        colorEntry(darkHighValue, [darkAppearance, highContrast]),
      );
    }
    sets[name] = json({ colors, info: xcodeInfo });
  }
  return sets;
}

