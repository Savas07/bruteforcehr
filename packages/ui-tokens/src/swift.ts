/**
 * Swift package output: `packages/ui-tokens/swift/BFHRDesignTokens`, consumed
 * by the iOS app as a local package. `renderSwiftPackage()` returns every file
 * of the package (path relative to the package root → contents); the files are
 * committed, `scripts/generate-swift.ts` writes them and `scripts/check-swift.ts`
 * (plus `swift.test.ts`) fails when they drift from this generator.
 *
 * - Colors: an asset catalog with one color set per token (`surface-canvas`,
 *   `status-offer-text`, the same names as the CSS variables), light + dark, and
 *   `contrast: high` variants for the `increasedContrast` roles. `Tokens.swift`
 *   exposes them as SwiftUI `Color`s, next to the iOS system colors the HIG
 *   expects (apple.ts).
 * - Type: each style mapped to its `Font.TextStyle`, so Dynamic Type scales it.
 * - Spacing, radius, borders, icon sizes, hit targets, elevation, motion (with
 *   Reduce Motion variants), timing and haptics.
 */
